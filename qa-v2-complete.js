const fs = require('fs');
const path = require('path');

class QATestRunner {
  constructor() {
    this.tests = [];
    this.results = {
      passed: 0,
      failed: 0,
      total: 0
    };
    this.failures = [];
  }

  test(name, fn) {
    this.tests.push({ name, fn });
  }

  async run() {
    console.log('\n🚀 DigiSchool Africa - QA Test Suite V2.0');
    console.log('Mode: GENSPARK.AI ONE-SHOT LOCKED SHIP\n');

    for (const test of this.tests) {
      this.results.total++;
      try {
        await test.fn();
        this.results.passed++;
        console.log(`✅ ${test.name}`);
      } catch (error) {
        this.results.failed++;
        this.failures.push({ test: test.name, error: error.message });
        console.log(`❌ ${test.name}: ${error.message}`);
      }
    }

    this.generateReport();
  }

  async checkFileExists(filePath) {
    return fs.existsSync(path.join(__dirname, filePath));
  }

  async checkFileContains(filePath, searchString) {
    const fullPath = path.join(__dirname, filePath);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`File ${filePath} not found`);
    }
    const content = fs.readFileSync(fullPath, 'utf-8');
    if (!content.includes(searchString)) {
      throw new Error(`File ${filePath} does not contain "${searchString}"`);
    }
  }

  async checkFileNotContains(filePath, searchString) {
    const fullPath = path.join(__dirname, filePath);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`File ${filePath} not found`);
    }
    const content = fs.readFileSync(fullPath, 'utf-8');
    if (content.includes(searchString)) {
      throw new Error(`File ${filePath} should NOT contain "${searchString}"`);
    }
  }

  generateReport() {
    console.log('\n' + '='.repeat(60));
    console.log('📊 TEST RESULTS');
    console.log('='.repeat(60));
    console.log(`Total: ${this.results.total}`);
    console.log(`✅ Passed: ${this.results.passed}`);
    console.log(`❌ Failed: ${this.results.failed}`);
    console.log(`Success Rate: ${((this.results.passed / this.results.total) * 100).toFixed(1)}%`);

    if (this.failures.length > 0) {
      console.log('\n❌ FAILURES:');
      this.failures.forEach((failure, idx) => {
        console.log(`${idx + 1}. ${failure.test}`);
        console.log(`   ${failure.error}\n`);
      });
    }

    console.log('='.repeat(60));

    // Write report to file
    const report = {
      timestamp: new Date().toISOString(),
      version: '2.0.0',
      mode: 'GENSPARK.AI ONE-SHOT LOCKED SHIP',
      results: this.results,
      failures: this.failures
    };

    fs.writeFileSync(
      path.join(__dirname, 'QA_REPORT_V2.json'),
      JSON.stringify(report, null, 2)
    );

    console.log('\n✅ Report saved: QA_REPORT_V2.json\n');

    // Write markdown report
    this.generateMarkdownReport();

    process.exit(this.results.failed > 0 ? 1 : 0);
  }

  generateMarkdownReport() {
    const md = `# QA Report V2.0 - DigiSchool Africa

**Mode:** GENSPARK.AI ONE-SHOT LOCKED SHIP  
**Date:** ${new Date().toISOString()}  
**Version:** 2.0.0

## Summary

- **Total Tests:** ${this.results.total}
- **Passed:** ✅ ${this.results.passed}
- **Failed:** ❌ ${this.results.failed}
- **Success Rate:** ${((this.results.passed / this.results.total) * 100).toFixed(1)}%

## Test Categories

### 1. Design System & Assets
- Global design CSS
- Header/Footer JS
- Course illustrations (9 courses)
- Logo files
- Social proof data

### 2. New Features
- Referral/parrainage system
- Auto-evaluation recommender
- Chatbot integration
- WhatsApp assistant
- About page

### 3. Payment Gating Rules
- No payment numbers on index.html
- No payment numbers on b2c.html
- No payment numbers on companies.html
- Payment numbers ONLY on b2c-checkout.html

### 4. Navigation & SEO
- Sitemap includes new pages
- Social links configured
- Header/footer consistent

### 5. Analytics Events
- All new tracking events

${this.failures.length > 0 ? `
## ❌ Failures

${this.failures.map((f, i) => `${i + 1}. **${f.test}**  
   ${f.error}`).join('\n\n')}
` : ''}

## Conclusion

${this.results.failed === 0 
  ? '✅ **ALL TESTS PASSED** - Platform is production-ready for January 19, 2026 launch.' 
  : `⚠️ **${this.results.failed} TEST(S) FAILED** - Review and fix issues before deployment.`}

---

*Generated by DigiSchool QA Test Suite V2.0*
`;

    fs.writeFileSync(path.join(__dirname, 'QA_REPORT_V2.md'), md);
    console.log('✅ Markdown report saved: QA_REPORT_V2.md');
  }
}

